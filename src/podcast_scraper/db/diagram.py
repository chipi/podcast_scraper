"""The physical database diagram, generated from the table definitions (ADR-169).

Every repo that owns tables renders its own metadata with this, and a test compares the committed
file with a fresh render, so a diagram cannot drift from the schema. Public renders the kernel and
the ``shared`` schema; a module renders its own tables.

    python -m podcast_scraper.db.diagram --out docs/architecture/diagrams/database-kernel.md
    python -m podcast_scraper.db.diagram --check docs/architecture/diagrams/database-kernel.md
    python -m podcast_scraper.db.diagram --metadata my_module.db.schema:metadata --title "…" --out …

The output is Markdown with one Mermaid ``erDiagram`` (rendered by MkDocs and by GitHub), then a
list of every table's constraints and indexes, which an ER diagram does not show.
"""

from __future__ import annotations

import argparse
import importlib
import sys
from collections.abc import Sequence
from pathlib import Path

from sqlalchemy import CheckConstraint, Column, MetaData, Table, UniqueConstraint

HEADER = "<!-- Generated by `python -m podcast_scraper.db.diagram`; do not edit by hand. -->"


def _type_name(column: Column) -> str:
    try:
        name = str(column.type.compile())
    except Exception:  # noqa: BLE001 - a type without a generic compile (JSONB, ARRAY)
        name = type(column.type).__name__
    # Mermaid attribute types are one word.
    return name.replace(" ", "_").replace("(", "_").replace(")", "").replace(",", "_").lower()


def _keys(column: Column) -> str:
    keys = []
    if column.primary_key:
        keys.append("PK")
    if column.foreign_keys:
        keys.append("FK")
    if column.unique or any(
        isinstance(c, UniqueConstraint) and [col.name for col in c.columns] == [column.name]
        for c in column.table.constraints
    ):
        keys.append("UK")
    return ",".join(keys)


def _entity(table: Table) -> str:
    return table.name if table.schema is None else f"{table.schema}_{table.name}"


def _label(table: Table) -> str:
    return table.name if table.schema is None else f"{table.schema}.{table.name}"


def _er(tables: list[Table]) -> list[str]:
    lines = ["```mermaid", "erDiagram"]
    for table in tables:
        lines.append(f'    {_entity(table)}["{_label(table)}"] {{')
        for column in table.columns:
            keys = _keys(column)
            null = "" if column.nullable is False or column.primary_key else ' "nullable"'
            lines.append(
                f"        {_type_name(column)} {column.name}{(' ' + keys) if keys else ''}{null}"
            )
        lines.append("    }")
    names = {t.name: t for t in tables}
    for table in tables:
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            target = names.get(fk.column.table.name)
            if target is None:
                continue
            cardinality = "|o--o{" if fk.parent.nullable else "||--o{"
            on_delete = f" ({fk.ondelete.lower()})" if fk.ondelete else ""
            edge = f"{_entity(target)} {cardinality} {_entity(table)}"
            lines.append(f'    {edge} : "{fk.parent.name}{on_delete}"')
    lines.append("```")
    return lines


def _constraints(tables: list[Table]) -> list[str]:
    lines = ["| Table | Constraints and indexes |", "| --- | --- |"]
    for table in tables:
        items: list[str] = []
        for c in sorted(table.constraints, key=lambda c: str(c.name or "")):
            if isinstance(c, CheckConstraint):
                items.append(f"CHECK `{c.name}`: `{c.sqltext}`")
            elif isinstance(c, UniqueConstraint):
                items.append(f"UNIQUE `{c.name}` ({', '.join(col.name for col in c.columns)})")
        for index in sorted(table.indexes, key=lambda i: str(i.name)):
            where = index.dialect_options["postgresql"].get("where")
            cols = ", ".join(str(e.name if hasattr(e, "name") else e) for e in index.expressions)
            items.append(
                f"INDEX `{index.name}` ({cols}){f' WHERE `{where}`' if where is not None else ''}"
            )
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            items.append(
                f"FK `{fk.parent.name}` → `{fk.target_fullname}`"
                + (f" ON DELETE {fk.ondelete}" if fk.ondelete else "")
            )
        lines.append(f"| `{_label(table)}` | {'<br>'.join(items) if items else '—'} |")
    return lines


def render(metadatas: Sequence[MetaData], title: str) -> str:
    """The diagram document for ``metadatas``, tables in definition order."""
    tables = [t for md in metadatas for t in md.tables.values()]
    body = [
        HEADER,
        "",
        f"# {title}",
        "",
        "Tables without a schema live in each plane's schema (`player`, `operator`); the "
        "`schema_translate_map` of the process's engine places them. Tables with a schema "
        "name it.",
        "",
        *_er(tables),
        "",
        "## Constraints and indexes",
        "",
        *_constraints(tables),
        "",
    ]
    return "\n".join(body)


def _load(spec: str) -> MetaData:
    module_name, _, attr = spec.partition(":")
    found = getattr(importlib.import_module(module_name), attr or "metadata")
    if not isinstance(found, MetaData):
        raise SystemExit(f"{spec} is not a SQLAlchemy MetaData")
    return found


KERNEL = ("podcast_scraper.db.schema:metadata", "podcast_scraper.db.schema:shared_metadata")
KERNEL_TITLE = "Kernel and shared schema: the physical diagram"


def main(argv: Sequence[str] | None = None) -> int:
    """Write the diagram to ``--out``, or exit 1 when ``--check`` finds the file stale."""
    parser = argparse.ArgumentParser(prog="python -m podcast_scraper.db.diagram")
    parser.add_argument("--metadata", action="append", help="module:attr of a MetaData (repeat)")
    parser.add_argument("--title", default=None)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--out", type=Path)
    target.add_argument("--check", type=Path)
    args = parser.parse_args(argv)
    specs = args.metadata or list(KERNEL)
    text = render([_load(s) for s in specs], args.title or KERNEL_TITLE)
    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        return 0
    current = args.check.read_text(encoding="utf-8") if args.check.is_file() else ""
    if current != text:
        print(
            f"{args.check} is stale; regenerate: python -m podcast_scraper.db.diagram "
            f"--out {args.check}",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
